def test_supported_module_exports_are_frozen():
    modules = (
        beamz,
        analysis,
        design,
        modes,
        monitors,
        sources,
        optimization,
        simulation,
    )
    for module in modules:
        expected = EXPECTED_EXPORTS[module.__name__]
        assert tuple(module.__all__) == expected
        assert all(hasattr(module, name) for name in expected)
